/* EBYTE */
#define USER_DMA_BUFF_SIZE 255

/* 固件版本号：每次发布前手动递增 */
#define FIRMWARE_VERSION    "v1.8.1"

static uint8_t rx_buffer[USER_DMA_BUFF_SIZE];
static uint8_t rx_ready_buffer[USER_DMA_BUFF_SIZE];
static uint8_t rx_process_buffer[USER_DMA_BUFF_SIZE];
static uint8_t rx_process_length;
static volatile uint8_t rx_length = 0;

static void User_UART1_StartRx(void)
{
    if (HAL_UARTEx_ReceiveToIdle_DMA(&huart1, rx_buffer, USER_DMA_BUFF_SIZE) == HAL_OK)
    {
      __HAL_DMA_DISABLE_IT(huart1.hdmarx, DMA_IT_HT);
    }
}

void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t size)
{
    if (huart->Instance == USART1)
    {
      if ((size > 0U) && (size <= USER_DMA_BUFF_SIZE) && (rx_length == 0U))
      {
        memcpy(rx_ready_buffer, rx_buffer, size);
        rx_length = (uint8_t)size;
      }
      User_UART1_StartRx();
    }
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    TTL_UART2_Router_RxCpltCallback(huart);
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART1)
    {
      huart1.RxState = HAL_UART_STATE_READY;
      User_UART1_StartRx();
    }
    else
    {
      TTL_UART2_Router_ErrorCallback(huart);
    }
}

